"""Helpers that read EA source and write the .set and tester .ini files."""
import re
from pathlib import Path

import config


def read_text_any(path: Path) -> str:
    """Read a text file that may be UTF-16 (MetaTrader logs/reports) or UTF-8."""
    raw = Path(path).read_bytes()
    if raw.startswith((b"\xff\xfe", b"\xfe\xff")):
        return raw.decode("utf-16", errors="replace")
    try:
        return raw.decode("utf-8-sig")
    except UnicodeDecodeError:
        return raw.decode("latin-1", errors="replace")


# input / sinput declarations: `input double Lots = 0.1;` (type may be an enum)
_INPUT_RE = re.compile(
    r"^\s*(?:input|sinput)\s+[\w:<>]+(?:\s+[\w:<>]+)*?\s+(\w+)\s*=\s*([^;/]+?)\s*;",
    re.MULTILINE,
)


def parse_inputs(source: str) -> dict:
    """Best-effort map of EA input name -> default value from the source text."""
    inputs = {}
    for name, default in _INPUT_RE.findall(source):
        inputs[name] = default.strip().strip('"')
    return inputs


def write_set_file(path: Path, inputs: dict) -> None:
    """Write a tester .set file: UTF-16 LE with BOM, one Name=Value per line."""
    lines = ["; generated by mt5 backtest bot"]
    lines += [f"{name}={value}" for name, value in inputs.items()]
    with open(path, "w", encoding="utf-16", newline="") as fh:
        fh.write("\r\n".join(lines) + "\r\n")


def write_tester_ini(path: Path, *, expert_rel: str, set_name: str, settings: dict,
                     report_rel: str) -> None:
    """Write the [Tester] ini that `terminal64.exe /config:` consumes."""
    lines = []
    if config.MT5_LOGIN and config.MT5_SERVER:
        lines += ["[Common]", f"Login={config.MT5_LOGIN}"]
        if config.MT5_PASSWORD:
            lines.append(f"Password={config.MT5_PASSWORD}")
        lines += [f"Server={config.MT5_SERVER}", ""]
    lines += ["[Tester]", f"Expert={expert_rel}"]
    if set_name:
        lines.append(f"ExpertParameters={set_name}")
    lines += [
        f"Symbol={settings['symbol']}",
        f"Period={settings['period']}",
        f"Model={settings['model']}",
        "ExecutionMode=0",
        "Optimization=0",
        f"FromDate={settings['from_date']}",
        f"ToDate={settings['to_date']}",
        "ForwardMode=0",
        f"Deposit={settings['deposit']}",
        f"Currency={settings['currency']}",
        f"Leverage={settings['leverage']}",
        "Visual=0",
        f"Report={report_rel}",
        "ReplaceReport=1",
        "ShutdownTerminal=1",
        "UseLocal=1",
        "UseRemote=0",
        "UseCloud=0",
    ]
    Path(path).write_text("\r\n".join(lines) + "\r\n", encoding="utf-8")
